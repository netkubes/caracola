defmodule Caracola.Call.UAC do
  @moduledoc false
  # Client transactions: sending requests and processing responses. Port of
  # NkSIP's nksip_call_uac, nksip_call_uac_send, nksip_call_uac_resp,
  # nksip_call_uac_reply and nksip_call_uac_timer.

  require Logger

  alias Caracola.{Call, Dialog, Message, Reply, Serializer, Subscription, Util, Via}

  alias Caracola.Call.{
    Auth,
    DialogUAC,
    Event,
    Fork,
    Make,
    Proxy,
    SessionTimer,
    Timers,
    Trans,
    Transp
  }

  ## ===================================================================
  ## Sending
  ## ===================================================================

  @doc false
  # New request from the API (`from` gets the result) or generated by the
  # call itself (`from` is nil)
  def send_new(method, uri, opts, from, %Call{} = call) do
    case Make.request(call, method, uri, opts) do
      {:ok, req, opts} ->
        req = %{req | dialog_id: Dialog.id(:uac, req)}
        {id, call} = Call.new_trans_id(call)
        {uac, call} = new_trans(id, req, opts, from, call)
        if :async in opts and method != :ack, do: Call.reply(from, {:async, handle(req)})
        send_request(uac, call)

      {:error, error} ->
        Call.reply(from, {:error, error})
        call
    end
  end

  @doc false
  # New in-dialog request
  def send_dialog(dialog_id, method, opts, from, %Call{} = call) do
    case DialogUAC.make(dialog_id, method, opts, call) do
      {:ok, ruri, opts, call} ->
        send_new(method, ruri, opts, from, call)

      {:error, error} ->
        Call.reply(from, {:error, error})
        call
    end
  end

  @doc false
  # Request proxied by a fork, with an already allocated transaction id
  def send_proxy(id, %Message{} = req, opts, fork_id, %Call{} = call) do
    {uac, call} = new_trans(id, req, opts, {:fork, fork_id}, call)
    send_request(uac, call)
  end

  defp new_trans(id, %Message{class: {:req, method}} = req, opts, from, call) do
    uac = %Trans{
      id: id,
      class: :uac,
      status:
        case method do
          :ack -> :ack
          :invite -> :invite_calling
          _ -> :trying
        end,
      from: from,
      opts: opts,
      request: req,
      method: method,
      ruri: req.ruri,
      start_time: System.monotonic_time()
    }

    {uac, call |> Call.update(uac) |> Call.put_msg(req, id)}
  end

  defp send_request(%Trans{request: req, opts: opts} = uac, call) do
    with :ok <- pre_dialog(uac, call),
         {:ok, req} <- Transp.send_request(req, opts, call.config) do
      uac = %{uac | request: req, transport: req.port.transport, trans_id: transaction_id(req)}
      call = if dialog?(uac), do: DialogUAC.request(req, call), else: call
      call = if new_subscription?(uac), do: Event.create_prov_event(req, call), else: call
      sent(uac, call)
    else
      {:error, error} when error in [:unknown_dialog, :request_pending, :unknown_subscription] ->
        uac = %{uac | status: :finished}
        reply({:error, error}, uac, Call.update(call, uac))

      {:error, error} ->
        Logger.info("error sending #{Message.method_to_string(uac.method)}: #{inspect(error)}")
        uac = %{uac | status: :finished}
        reply({:error, :service_unavailable}, uac, Call.update(call, uac))
    end
  end

  # Requests inside a dialog update it, unless sent with :no_dialog
  defp dialog?(%Trans{request: req, opts: opts}),
    do: req.to_tag != nil and :no_dialog not in opts

  # A NOTIFY can arrive before the response to a SUBSCRIBE outside a dialog
  defp new_subscription?(%Trans{method: method, request: req, opts: opts}),
    do: method in [:subscribe, :refer] and req.to_tag == nil and :no_dialog not in opts

  defp pre_dialog(uac, call),
    do: if(dialog?(uac), do: DialogUAC.pre_request(uac.request, call), else: :ok)

  defp sent(%Trans{method: :ack} = uac, call) do
    uac = %{uac | status: :finished}
    reply({:req, uac.request}, uac, Call.update(call, uac))
  end

  defp sent(%Trans{method: :invite} = uac, call) do
    uac =
      %{uac | status: :invite_calling}
      |> Timers.expire(:expire)
      |> Timers.timeout(:timer_b, call)

    uac = if uac.transport == :udp, do: Timers.retrans(uac, :timer_a, call), else: uac
    reply({:req, uac.request}, uac, Call.update(call, uac))
  end

  defp sent(uac, call) do
    uac = Timers.timeout(%{uac | status: :trying}, :timer_f, call)
    uac = if uac.transport == :udp, do: Timers.retrans(uac, :timer_e, call), else: uac
    reply({:req, uac.request}, uac, Call.update(call, uac))
  end

  @doc false
  # Client transaction id (RFC 3261 §17.1.3)
  def transaction_id(%Message{cseq: {_, method}, vias: [via | _]}) do
    {:ok, branch} = Via.get_param(via, "branch")
    :erlang.phash2({method, branch})
  end

  def transaction_id(%Message{}), do: nil

  @doc false
  def handle(%Message{service: service, call_id: call_id, id: id}), do: {service, call_id, id}

  ## ===================================================================
  ## CANCEL
  ## ===================================================================

  @doc false
  def cancel_id(msg_id, opts, call) do
    case Call.trans_by_msg(call, msg_id) do
      {:ok, %Trans{class: :uac, method: :invite} = uac} -> {:ok, cancel(uac, opts, call)}
      _ -> {{:error, :unknown_request}, call}
    end
  end

  @doc false
  # The CANCEL is sent once a provisional response has been received
  def cancel(%Trans{status: :invite_calling, cancel: nil} = uac, _opts, call),
    do: Call.update(call, %{uac | cancel: :to_cancel})

  def cancel(%Trans{status: :invite_proceeding, cancel: cancel} = uac, opts, call)
      when cancel in [nil, :to_cancel] do
    cancel_req = Make.cancel(uac.request, opts)
    call = Call.update(call, %{uac | cancel: :cancelled})
    {id, call} = Call.new_trans_id(call)
    {cancel_uac, call} = new_trans(id, cancel_req, [:no_dialog], nil, call)

    case Transp.send_same_path(cancel_req, uac.request) do
      {:ok, req} ->
        sent(
          %{
            cancel_uac
            | request: req,
              transport: req.port.transport,
              trans_id: transaction_id(req)
          },
          call
        )

      {:error, _} ->
        Call.update(call, %{cancel_uac | status: :finished})
    end
  end

  def cancel(_uac, _opts, call), do: call

  ## ===================================================================
  ## Responses
  ## ===================================================================

  @doc false
  def response(%Message{} = resp, %Call{} = call) do
    case Call.find_trans(call, :uac, transaction_id(resp)) do
      %Trans{} = uac ->
        resp = %{resp | ruri: uac.ruri, dialog_id: Dialog.id(:uac, resp)}
        if prack_retrans?(resp, uac), do: call, else: do_response(resp, uac, call)

      nil ->
        if Transp.stateless?(resp) do
          Proxy.response_stateless(resp, call)
        else
          Logger.info("received response for unknown transaction")
          call
        end
    end
  end

  defp do_response(resp, uac, call) do
    resp =
      if match?({:fork, _}, uac.from) and SessionTimer.enabled?(call.config),
        do: SessionTimer.proxy_response(uac.request, resp),
        else: resp

    # Responses to SUBSCRIBE need not have an Event (RFC 6665): the one of
    # the request identifies their subscription
    resp =
      if uac.method == :subscribe and not match?({:fork, _}, uac.from),
        do: %{resp | event: uac.request.event},
        else: resp

    {:resp, code, _} = resp.class
    if code >= 200 and uac.code < 200, do: Call.telemetry(:uac, uac, code, call)
    uac = %{uac | response: resp, code: code}
    call = call |> Call.put_msg(resp, uac.id) |> Call.update(uac)
    call = response_effects(resp, code, uac, call)
    response_status(uac.status, resp, uac, call)
  end

  # Dialogs, provisional events, authorized origins and GRUUs
  defp response_effects(resp, code, uac, call) do
    call =
      if :no_dialog in uac.opts,
        do: call,
        else: DialogUAC.response(uac.request, resp, call)

    call =
      if code >= 300 and uac.method in [:subscribe, :refer],
        do: Event.remove_prov_event(uac.request, call),
        else: call

    if Caracola.Gruu.enabled?(call.config), do: Caracola.Gruu.uac_response(resp, call.config)

    # The origin of a 2xx is authorized in the dialog
    if code in 200..299, do: Auth.update(call, resp), else: call
  end

  defp response_status(:invite_calling, resp, uac, call) do
    uac = Timers.retrans(%{uac | status: :invite_proceeding}, :cancel, call)
    response_status(:invite_proceeding, resp, uac, Call.update(call, uac))
  end

  defp response_status(:invite_proceeding, resp, %Trans{code: code} = uac, call)
       when code < 200 do
    uac = Timers.timeout(uac, :timer_c, call)
    call = reply({:resp, resp}, uac, Call.update(call, uac))
    call = if reliable?(resp, uac, call), do: send_prack(resp, uac, call), else: call
    if uac.cancel == :to_cancel, do: cancel(uac, [], call), else: call
  end

  # RFC 6026 accepted state, absorbs 2xx retransmissions
  defp response_status(:invite_proceeding, resp, %Trans{code: code} = uac, call)
       when code < 300 do
    call = reply({:resp, resp}, uac, call)

    uac =
      %{uac | status: :invite_accepted, cancel: nil, response: nil, to_tags: [resp.to_tag]}
      |> Timers.expire(:cancel)
      |> Timers.timeout(:timer_m, call)

    call = Call.update(call, uac)

    if :auto_2xx_ack in uac.opts,
      do: send_dialog(resp.dialog_id, :ack, [], nil, call),
      else: call
  end

  # Own generated final response (timeout)
  defp response_status(:invite_proceeding, %Message{port: nil} = resp, uac, call) do
    call = reply({:resp, resp}, uac, call)
    Call.update(call, %{uac | status: :finished})
  end

  defp response_status(:invite_proceeding, resp, uac, call) do
    uac =
      %{uac | to_tags: [resp.to_tag], cancel: nil}
      |> Timers.timeout(:cancel, call)
      |> Timers.expire(:cancel)

    send_ack(uac, resp)

    uac =
      if uac.transport == :udp,
        do: Timers.timeout(%{uac | status: :invite_completed, response: nil}, :timer_d, call),
        else: %{uac | status: :finished}

    reply({:resp, resp}, uac, Call.update(call, uac))
  end

  # A 2xx from another fork: its dialog is confirmed and ended at once
  defp response_status(:invite_accepted, resp, %Trans{code: code} = uac, call)
       when code in 200..299 do
    if resp.to_tag in uac.to_tags do
      call
    else
      Logger.info("sending ACK and BYE to secondary 2xx response from #{resp.to_tag}")
      call = send_dialog(resp.dialog_id, :ack, [], nil, call)
      call = send_dialog(resp.dialog_id, :bye, [], nil, call)
      Call.update(call, %{uac | to_tags: uac.to_tags ++ [resp.to_tag]})
    end
  end

  # Retransmission of the final response: the ACK is sent again
  defp response_status(:invite_completed, resp, %Trans{to_tags: [tag | _]} = uac, call) do
    if resp.to_tag == tag, do: send_ack(uac, resp)
    call
  end

  defp response_status(:trying, resp, uac, call) do
    uac = Timers.retrans(%{uac | status: :proceeding}, :cancel, call)
    response_status(:proceeding, resp, uac, Call.update(call, uac))
  end

  defp response_status(:proceeding, resp, %Trans{code: code} = uac, call) when code < 200,
    do: reply({:resp, resp}, uac, call)

  defp response_status(:proceeding, %Message{port: nil} = resp, uac, call) do
    call = reply({:resp, resp}, uac, call)
    Call.update(call, %{uac | status: :finished})
  end

  defp response_status(:proceeding, resp, uac, call) do
    uac =
      if uac.transport == :udp,
        do:
          Timers.timeout(
            %{uac | status: :completed, response: nil, to_tags: [resp.to_tag]},
            :timer_k,
            call
          ),
        else: %{uac | status: :finished}

    reply({:resp, resp}, uac, Call.update(call, uac))
  end

  defp response_status(_status, _resp, _uac, call), do: call

  defp send_ack(%Trans{request: req}, resp) do
    with {:error, error} <- Transp.send_same_path(Make.ack(req, resp), req),
         do: Logger.notice("could not send ACK: #{inspect(error)}")
  end

  ## ===================================================================
  ## PRACK (RFC 3262)
  ## ===================================================================

  # Reliable provisional responses get a PRACK, if 100rel is supported
  defp reliable?(resp, %Trans{from: from}, call) do
    "100rel" in resp.require and "100rel" in (call.config[:supported] || []) and
      not match?({:fork, _}, from)
  end

  defp prack_retrans?(%Message{class: {:resp, code, _}} = resp, uac) when code in 101..199 do
    case rseq(resp) do
      {:ok, rseq} -> {rseq, resp.cseq, resp.dialog_id} in uac.pracks
      :error -> false
    end
  end

  defp prack_retrans?(_resp, _uac), do: false

  defp rseq(resp) do
    with [value] <- Message.header(resp, "rseq"),
         {rseq, ""} when rseq > 0 <- Integer.parse(value) do
      {:ok, rseq}
    else
      _ -> :error
    end
  end

  # RSeq values must be consecutive. The prack_callback option can give the
  # SDP of the PRACK (an answer to an offer in the response, or a new offer).
  defp send_prack(%Message{cseq: {cseq, method}} = resp, %Trans{id: id}, call) do
    uac = Map.fetch!(call.trans, id)

    with {:ok, rseq} <- rseq(resp),
         true <- uac.rseq == 0 or rseq == uac.rseq + 1,
         rack = "#{rseq} #{cseq} #{Message.method_to_string(method)}",
         opts = [{:add, "rack", rack} | prack_body(resp, uac, call)],
         {:ok, ruri, opts, call} <- DialogUAC.make(resp.dialog_id, :prack, opts, call) do
      uac = %{uac | rseq: rseq, pracks: [{rseq, resp.cseq, resp.dialog_id} | uac.pracks]}
      send_new(:prack, ruri, opts, nil, Call.update(call, uac))
    else
      error ->
        Logger.warning("could not send PRACK: #{inspect(error)}")
        call
    end
  end

  defp prack_body(%Message{class: {:resp, code, _}} = resp, uac, call) do
    case Util.opt(uac.opts, :prack_callback) do
      fun when is_function(fun, 2) ->
        case fun.(DialogUAC.remote_offer(resp.dialog_id, call), {:resp, code, resp}) do
          %Caracola.SDP{} = sdp -> [body: sdp]
          body when is_binary(body) and body != "" -> [body: body]
          _ -> []
        end

      _ ->
        []
    end
  end

  ## ===================================================================
  ## Results
  ## ===================================================================

  # Responses of proxied requests go to their fork
  defp reply({:resp, resp}, %Trans{from: {:fork, fork_id}} = uac, call),
    do: Fork.response(fork_id, uac.id, resp, call)

  defp reply({:error, _error}, %Trans{from: {:fork, fork_id}} = uac, call) do
    {resp, _} = Reply.make!(uac.request, :service_unavailable, call.config)
    Fork.response(fork_id, uac.id, resp, call)
  end

  defp reply({:req, _req}, %Trans{from: {:fork, _}}, call), do: call

  # Session interval too small: sent again with the Min-SE of the response
  defp reply({:resp, %Message{class: {:resp, 422, _}} = resp} = class, uac, call)
       when uac.method in [:invite, :update] do
    current = Call.Dialog.get_meta(resp.dialog_id, :min_se, call)

    with true <- SessionTimer.enabled?(call.config),
         {:ok, req, min_se} <-
           SessionTimer.retry_422(uac.request, resp, uac.iter, current, call.config) do
      resend(req, uac, Call.Dialog.put_meta(resp.dialog_id, :min_se, min_se, call))
    else
      _ -> report_reply(class, uac, call)
    end
  end

  # Challenges are answered with the available passwords
  defp reply({:resp, %Message{class: {:resp, code, _}} = resp} = class, uac, call)
       when code in [401, 407] and uac.method not in [:cancel, :ack] do
    passwords =
      Auth.passwords(Util.opt(uac.opts, :password)) ++ Auth.passwords(call.config[:password])

    max = call.config[:auto_auth_max_tries] || 5

    with true <- passwords != [] and uac.iter < max,
         {:ok, req} <- Auth.credentials(uac.request, resp, passwords) do
      resend(req, uac, call)
    else
      _ -> report_reply(class, uac, call)
    end
  end

  defp reply(class, uac, call), do: report_reply(class, uac, call)

  # A new transaction for the same request (with a new CSeq), replying to
  # the same caller
  defp resend(%Message{class: {:req, method}, vias: [_ | vias]} = req, uac, call) do
    {cseq, call} = DialogUAC.next_cseq(req, call)
    req = %{req | vias: vias, id: Util.uid(), cseq: {cseq, method}}
    {id, call} = Call.new_trans_id(call)
    {new_uac, call} = new_trans(id, req, uac.opts, uac.from, call)
    send_request(%{new_uac | iter: uac.iter + 1}, Call.move_msgs(call, uac.id, id))
  end

  # Reports to the caller: the request (if :get_request), provisional
  # responses (to the callback) and the final response or error
  defp report_reply(class, %Trans{from: from, opts: opts} = uac, call) when from != nil do
    report(class, uac, Util.opt(opts, :callback), :async in opts)
    refer_notify(class, Util.opt(opts, :refer_subscription))
    call
  end

  defp report_reply(_class, _uac, call), do: call

  defp report({:req, req}, uac, callback, async?) do
    if callback && :get_request in uac.opts, do: safe(callback, {:req, req})
    if uac.method == :ack and not async?, do: GenServer.reply(uac.from, :ok)
  end

  defp report({:resp, %Message{class: {:resp, code, _}} = resp}, uac, callback, async?) do
    if callback && code > 100 && (code < 200 or async?), do: safe(callback, {:resp, code, resp})

    if code >= 200 and not async?,
      do: GenServer.reply(uac.from, {:ok, code, metas(resp, uac.opts)})
  end

  defp report({:error, error}, uac, callback, async?) do
    if callback && async?, do: safe(callback, {:error, error})
    if not async?, do: GenServer.reply(uac.from, {:error, error})
  end

  # A request started by a REFER (see Caracola.Refer) reports its progress
  # with NOTIFYs to the REFER subscription (RFC 3515 §2.4.5). They are sent
  # from another process, as the subscription lives in another call.
  defp refer_notify(_class, nil), do: :ok
  defp refer_notify({:req, _req}, _subs), do: :ok
  defp refer_notify({:resp, %Message{class: {:resp, 100, _}}}, _subs), do: :ok

  defp refer_notify(class, subs) do
    {code, reason} =
      case class do
        {:resp, %Message{class: {:resp, code, ""}}} -> {code, Serializer.reason_phrase(code)}
        {:resp, %Message{class: {:resp, code, reason}}} -> {code, reason}
        {:error, _error} -> {503, Serializer.reason_phrase(503)}
      end

    opts = [
      :async,
      content_type: "message/sipfrag;version=2.0",
      body: "SIP/2.0 #{code} #{reason}",
      subscription_state: if(code >= 200, do: {:terminated, :noresource}, else: :active)
    ]

    spawn(fn -> Caracola.UAC.notify(subs, opts) end)
    :ok
  end

  defp safe(fun, arg) do
    fun.(arg)
  rescue
    error -> Logger.warning("error in UAC callback: " <> Exception.message(error))
  end

  @doc false
  # Values requested with get_meta, after the dialog of INVITE responses
  def metas(%Message{} = msg, opts) do
    dialog =
      case msg do
        %Message{class: {:resp, code, _}, cseq: {_, :invite}} when code in 101..299 ->
          [dialog: Dialog.handle(msg)]

        %Message{class: {:resp, code, _}, cseq: {_, method}}
        when code in 200..299 and method in [:subscribe, :refer] ->
          [subscription: Subscription.handle_of(msg)]

        # The entity tag and expiration of a publication (RFC 3903)
        %Message{class: {:resp, code, _}, cseq: {_, :publish}} when code in 200..299 ->
          [sip_etag: List.first(Message.header(msg, "sip-etag")), expires: msg.expires]

        _ ->
          []
      end

    dialog ++ for meta <- Util.opt(opts, :get_meta, []), do: {meta, meta(msg, meta)}
  end

  defp meta(%Message{class: {:resp, code, ""}}, :reason_phrase),
    do: Caracola.Serializer.reason_phrase(code)

  defp meta(%Message{class: {:resp, _, reason}}, :reason_phrase), do: reason

  defp meta(msg, :code), do: elem(msg.class, 1)
  defp meta(msg, :port), do: msg.port
  defp meta(msg, :call_id), do: msg.call_id
  defp meta(msg, :from), do: msg.from
  defp meta(msg, :to), do: msg.to
  defp meta(msg, :from_tag), do: msg.from_tag
  defp meta(msg, :to_tag), do: msg.to_tag
  defp meta(msg, :cseq_num), do: elem(msg.cseq, 0)

  defp meta(msg, :rseq_num) do
    case rseq(msg) do
      {:ok, rseq} -> rseq
      :error -> nil
    end
  end

  defp meta(msg, :body), do: msg.body
  defp meta(msg, :contacts), do: msg.contacts
  defp meta(msg, :handle), do: handle(msg)
  defp meta(msg, :dialog), do: Dialog.handle(msg)
  defp meta(msg, :subscription), do: Subscription.handle_of(msg)
  defp meta(msg, :all_headers), do: msg.headers
  defp meta(msg, name) when is_binary(name), do: Message.header(msg, name)
  defp meta(_msg, _meta), do: nil

  ## ===================================================================
  ## Timers
  ## ===================================================================

  @doc false
  def timer(tag, %Trans{request: req} = uac, call) when tag in [:timer_a, :timer_e] do
    case Transp.resend_request(req) do
      {:ok, _} -> Call.update(call, Timers.retrans(uac, tag, call))
      {:error, _} -> local_response(uac, {:service_unavailable, "Resend Error"}, call)
    end
  end

  def timer(:timer_b, uac, call), do: local_response(uac, {:timeout, "Timer B Timeout"}, call)
  def timer(:timer_c, uac, call), do: local_response(uac, {:timeout, "Timer C Timeout"}, call)
  def timer(:timer_f, uac, call), do: local_response(uac, {:timeout, "Timer F Timeout"}, call)

  def timer(tag, uac, call) when tag in [:timer_d, :timer_k, :timer_m],
    do: Call.update(call, %{uac | status: :finished})

  def timer(:expire, %Trans{status: status} = uac, call)
      when status in [:invite_calling, :invite_proceeding] do
    uac = %{uac | status: :invite_proceeding}
    cancel(uac, [], Call.update(call, uac))
  end

  def timer(:expire, uac, call), do: Call.update(call, uac)

  # Generated response (408, 503) as if it had been received
  defp local_response(%Trans{request: req}, sipreply, call) do
    {resp, _} = Reply.make!(%{req | port: nil}, sipreply, call.config)
    response(resp, call)
  end
end
