defmodule Caracola.Call.UAS do
  @moduledoc false
  # Server transactions: processing of incoming requests and sending of
  # responses. Port of NkSIP's nksip_call_uas, nksip_call_uas_route,
  # nksip_call_uas_process, nksip_call_uas_reply and nksip_call_uas_timer.

  require Logger

  alias Caracola.{Call, Dialog, Message, Reply, Util, Via}
  alias Caracola.Call.{Auth, DialogUAS, Event, Fork, Proxy, SessionTimer, Timers, Trans, Transp}

  @in_dialog [:bye, :info, :prack, :update, :notify]

  @callbacks %{
    invite: :sip_invite,
    update: :sip_update,
    bye: :sip_bye,
    options: :sip_options,
    register: :sip_register,
    prack: :sip_prack,
    info: :sip_info,
    message: :sip_message,
    subscribe: :sip_subscribe,
    notify: :sip_notify,
    refer: :sip_refer,
    publish: :sip_publish
  }

  ## ===================================================================
  ## Incoming requests
  ## ===================================================================

  @doc false
  def request(%Message{} = req, %Call{} = call) do
    cond do
      inv = trans_ack(req, call) -> process_trans_ack(inv, call)
      uas = retrans(req, call) -> process_retrans(uas, call)
      own_ack?(req) -> call
      true -> process_request(req, call)
    end
  end

  # An ACK for a non-2xx final response belongs to the INVITE transaction
  defp trans_ack(%Message{class: {:req, :ack}} = req, call),
    do: Call.find_trans(call, :uas, transaction_id(req, :invite))

  defp trans_ack(_req, _call), do: nil

  defp process_trans_ack(%Trans{status: :invite_completed} = inv, call) do
    inv = Timers.retrans(%{inv | response: nil}, :cancel, call)

    inv =
      if inv.transport == :udp,
        do: Timers.timeout(%{inv | status: :invite_confirmed}, :timer_i, call),
        else: %{inv | status: :finished}

    Call.update(call, inv)
  end

  defp process_trans_ack(_inv, call), do: call

  defp retrans(req, call), do: Call.find_trans(call, :uas, transaction_id(req, nil))

  defp process_retrans(%Trans{status: status, response: %Message{} = resp}, call)
       when status in [:invite_proceeding, :invite_completed, :proceeding, :completed] do
    with {:error, error} <- Transp.resend_response(resp),
         do: Logger.info("could not retransmit response: #{inspect(error)}")

    call
  end

  defp process_retrans(_uas, call), do: call

  # ACK to a [3456]xx response generated by us (To tag derived from the branch)
  defp own_ack?(%Message{class: {:req, :ack}, to_tag: to_tag, vias: [via | _]})
       when is_binary(to_tag) do
    case Via.get_param(via, "branch") do
      {:ok, branch} when is_binary(branch) -> Util.hash({Util.global_id(), branch}) == to_tag
      _ -> false
    end
  end

  defp own_ack?(_req), do: false

  @doc false
  # Transaction id (RFC 3261 §17.2.3), or a negative one for pre-RFC 3261 requests
  def transaction_id(%Message{class: {:req, method}, vias: [via | _]} = req, as_method) do
    method = as_method || method
    port = via.port || 5060

    case Via.get_param(via, "branch") do
      {:ok, "z9hG4bK" <> rest = branch} when rest != "" ->
        :erlang.phash2({method, via.domain, port, branch})

      _ ->
        {cseq, _} = req.cseq

        -:erlang.phash2(
          {req.ruri.domain, req.ruri.port, req.from_tag, req.to_tag, cseq, method, via.domain,
           port}
        )
    end
  end

  defp process_request(%Message{class: {:req, method}} = req, call) do
    req = req |> preprocess() |> received_request(call)
    req = %{req | dialog_id: Dialog.id(:uas, req)}
    {id, call} = Call.new_trans_id(call)

    uas = %Trans{
      id: id,
      class: :uas,
      status: initial_status(method),
      trans_id: transaction_id(req, nil),
      request: req,
      method: method,
      ruri: req.ruri,
      transport: req.port.transport,
      stateless: true,
      loop_id: :erlang.phash2({req.from_tag, elem(req.cseq, 0), method}),
      start_time: System.monotonic_time()
    }

    uas = initial_timer(uas, call)

    looped? =
      req.to_tag == nil and
        Enum.any?(call.trans, fn {_, t} -> t.class == :uas and t.loop_id == uas.loop_id end)

    call = call |> Call.update(uas) |> Call.put_msg(req, id)

    if looped?, do: do_reply(:loop_detected, uas, call), else: send_100(uas, call)
  end

  # Plugins can change the requests they receive, before they are
  # authorized and routed (see caracola_received_request/2)
  defp received_request(req, call) do
    case Call.callback(call, :caracola_received_request, [req, call]) do
      %Message{} = req -> req
      _ -> req
    end
  end

  defp initial_status(:invite), do: :invite_proceeding
  defp initial_status(:ack), do: :ack
  defp initial_status(_), do: :trying

  defp initial_timer(%Trans{method: :invite} = uas, call), do: Timers.timeout(uas, :timer_c, call)
  defp initial_timer(%Trans{method: :ack} = uas, _call), do: uas
  defp initial_timer(uas, call), do: Timers.timeout(uas, :noinvite, call)

  # RFC 3581: the received parameter and, for connection oriented transports
  # or if requested, rport with the source port
  defp preprocess(%Message{vias: [via | vias], port: port} = req) do
    params = Enum.reject(via.params, fn {name, _} -> name in ["received", "rport"] end)
    rport? = port.transport != :udp or match?({:ok, _}, Via.get_param(via, "rport"))

    received = [
      {"received", Util.ip_to_host(port.remote_ip) |> String.trim("[") |> String.trim("]")}
    ]

    rport = if rport?, do: [{"rport", Integer.to_string(port.remote_port)}], else: []
    %{req | vias: [%{via | params: params ++ received ++ rport} | vias]}
  end

  defp send_100(%Trans{method: :invite, request: req} = uas, call) do
    if call.config[:no_100] do
      check_cancel(uas, call)
    else
      {resp, opts} = Reply.make!(req, 100, call.config)

      case Transp.send_response(resp, opts, call.config) do
        {:ok, _} -> check_cancel(uas, call)
        {:error, _} -> do_reply(:service_unavailable, uas, call)
      end
    end
  end

  defp send_100(uas, call), do: check_cancel(uas, call)

  defp check_cancel(%Trans{method: :cancel, request: req} = uas, call) do
    inv = Call.find_trans(call, :uas, transaction_id(req, :invite))

    cond do
      inv == nil or not same_source?(inv.request, req) ->
        authorize(uas, call)

      inv.status == :invite_proceeding ->
        call = do_reply(:ok, uas, call)
        Call.callback(call, :sip_cancel, [inv.request, req, call])
        cancel_invite(inv, call)

      true ->
        do_reply(:no_transaction, uas, call)
    end
  end

  defp check_cancel(uas, call), do: authorize(uas, call)

  # A proxied INVITE is cancelled downstream, the 487 comes from there
  defp cancel_invite(%Trans{from: {:fork, fork_id}}, call), do: Fork.cancel(fork_id, call)

  defp cancel_invite(inv, call) do
    inv = %{inv | cancel: :cancelled}
    do_reply(:request_terminated, inv, Call.update(call, inv))
  end

  defp same_source?(%Message{port: p1}, %Message{port: p2}),
    do: p1.remote_ip == p2.remote_ip and p1.remote_port == p2.remote_port

  # sip_authorize is called first with an empty list, and only if it does
  # not accept the request the credentials are checked (calling
  # sip_get_user_pass)
  defp authorize(%Trans{request: req} = uas, call) do
    reply =
      case Call.callback(call, :sip_authorize, [[], req, call]) do
        :ok -> :ok
        _ -> Call.callback(call, :sip_authorize, [Auth.authorize_data(req, call), req, call])
      end

    authorize_reply(reply, uas, call)
  end

  defp authorize_reply(:ok, %Trans{request: req} = uas, call) do
    call = if req.to_tag, do: Auth.update(call, req), else: call
    route(uas, call)
  end

  defp authorize_reply(:forbidden, uas, call), do: do_reply(:forbidden, uas, call)

  defp authorize_reply(reply, %Trans{request: req} = uas, call)
       when reply in [:authenticate, :proxy_authenticate] or
              (is_tuple(reply) and tuple_size(reply) == 2 and
                 elem(reply, 0) in [:authenticate, :proxy_authenticate]) do
    {type, realm} = if is_tuple(reply), do: reply, else: {reply, nil}

    {code, header} =
      if type == :authenticate,
        do: {401, "www-authenticate"},
        else: {407, "proxy-authenticate"}

    challenges = for value <- Auth.challenges(req, realm, call), do: {:add, header, value}
    do_reply({code, challenges}, uas, call)
  end

  defp authorize_reply(other, uas, call), do: invalid_reply(:sip_authorize, other, uas, call)

  defp route(%Trans{ruri: ruri, request: req} = uas, call) do
    reply = Call.callback(call, :sip_route, [ruri.scheme, ruri.user, ruri.domain, req, call])
    route_reply(reply, uas, call)
  end

  defp route_reply(:process, uas, call) do
    uas = %{uas | stateless: false}
    process(uas, Call.update(call, uas))
  end

  defp route_reply(:process_stateless, %Trans{method: :invite} = uas, call),
    do: invalid_reply(:sip_route, :process_stateless, uas, call)

  defp route_reply(:process_stateless, uas, call), do: process(uas, call)
  defp route_reply({:reply, reply}, uas, call), do: stateful_reply(reply, uas, call)
  defp route_reply({:reply_stateless, reply}, uas, call), do: do_reply(reply, uas, call)

  defp route_reply(:proxy, uas, call), do: proxy(:ruri, [], uas, call)
  defp route_reply({:proxy, uris}, uas, call), do: proxy(uris, [], uas, call)

  defp route_reply({:proxy, uris, opts}, uas, call) when is_list(opts),
    do: proxy(uris, opts, uas, call)

  defp route_reply(:proxy_stateless, uas, call), do: proxy(:ruri, [:stateless], uas, call)

  defp route_reply({:proxy_stateless, uris}, uas, call),
    do: proxy(uris, [:stateless], uas, call)

  defp route_reply({:proxy_stateless, uris, opts}, uas, call) when is_list(opts),
    do: proxy(uris, [:stateless | opts], uas, call)

  # Routed later with Caracola.route/2
  defp route_reply(:noreply, %Trans{method: method} = uas, call)
       when method not in [:ack, :cancel] do
    uas = %{uas | stateless: false, opts: [:async_route | uas.opts]}
    Call.update(call, uas)
  end

  defp route_reply(other, uas, call), do: invalid_reply(:sip_route, other, uas, call)

  @doc false
  # The route of a request whose sip_route/5 returned :noreply
  def route_id(msg_id, route, call) do
    case Call.trans_by_msg(call, msg_id) do
      {:ok, %Trans{class: :uas, status: status, opts: opts} = uas}
      when status in [:invite_proceeding, :trying] ->
        if :async_route in opts do
          uas = %{uas | opts: List.delete(opts, :async_route)}
          {:ok, route_reply(route, uas, Call.update(call, uas))}
        else
          {{:error, :invalid_request}, call}
        end

      _ ->
        {{:error, :invalid_request}, call}
    end
  end

  defp stateful_reply(reply, uas, call) do
    uas = %{uas | stateless: false}
    do_reply(reply, uas, Call.update(call, uas))
  end

  defp proxy(:ruri, opts, uas, call), do: proxy(uas.ruri, opts, uas, call)

  defp proxy(uris, opts, uas, call),
    do: check_session_timer(uas, call, &do_proxy(uris, opts, &1, &2))

  defp do_proxy(uris, opts, %Trans{method: method} = uas, call) do
    case Proxy.route(uris, opts, uas, call) do
      :noreply ->
        Call.update(call, %{uas | status: :finished})

      # A CANCEL is proxied only if stateless (otherwise it goes with its INVITE)
      {:fork, _req, _uri_set, _opts} when method == :cancel ->
        do_reply(:no_transaction, uas, call)

      {:fork, req, uri_set, opts} ->
        uas = %{uas | opts: [:no_dialog | uas.opts], stateless: false, from: {:fork, uas.id}}
        uas = if method == :ack, do: %{uas | status: :finished}, else: uas
        Fork.start(uas, req, uri_set, opts, Call.update(call, uas))

      {:reply, reply} ->
        do_reply(reply, uas, call)
    end
  end

  defp invalid_reply(fun, reply, uas, call) do
    Logger.warning("invalid reply from #{fun}: #{inspect(reply)}")
    do_reply({:internal_error, "Invalid Service Reply"}, uas, call)
  end

  ## ===================================================================
  ## Processing
  ## ===================================================================

  defp process(%Trans{method: method, request: req} = uas, call) when method in [:ack, :cancel],
    do: check_dialog(method, req, uas, call)

  defp process(%Trans{method: method, request: req} = uas, call) do
    supported = call.config[:supported] || []

    case Enum.reject(req.require, &(&1 in supported)) do
      [] -> check_session_timer(uas, call, &check_event(method, &1.request, &1, &2))
      unsupported -> do_reply({:bad_extension, Enum.join(unsupported, ",")}, uas, call)
    end
  end

  # Session interval too small (RFC 4028): 422, or a Min-SE for a request
  # that does not support timers. The Min-SE is remembered in the dialog.
  defp check_session_timer(%Trans{request: req} = uas, call, next) do
    if SessionTimer.enabled?(call.config) do
      case SessionTimer.check(req, call.config) do
        :ok ->
          next.(uas, call)

        {:reply, reply} ->
          do_reply(reply, uas, call)

        {:reply, reply, min_se} ->
          do_reply(reply, uas, Call.Dialog.put_meta(req.dialog_id, :min_se, min_se, call))

        {:update, req, min_se} ->
          uas = %{uas | request: req}
          call = Call.Dialog.put_meta(req.dialog_id, :min_se, min_se, call)
          next.(uas, Call.update(call, uas))
      end
    else
      next.(uas, call)
    end
  end

  # Without an event compositor, PUBLISH is not allowed
  defp check_event(:publish, req, uas, call) do
    allow = call.config[:allow] || []

    if "PUBLISH" in allow,
      do: check_event_type(:publish, req, uas, call),
      else: do_reply({:method_not_allowed, allow}, uas, call)
  end

  defp check_event(:subscribe, req, uas, call), do: check_event_type(:subscribe, req, uas, call)

  defp check_event(:notify, req, uas, call) do
    case Caracola.Subscription.state(req) do
      :invalid -> do_reply({:invalid_request, "Invalid Subscription-State"}, uas, call)
      _ -> check_dialog(:notify, req, uas, call)
    end
  end

  defp check_event(method, req, uas, call), do: check_dialog(method, req, uas, call)

  defp check_event_type(method, req, uas, call) do
    case req.event do
      {type, _} ->
        if type in ["refer" | call.config[:events] || []],
          do: check_dialog(method, req, uas, call),
          else: do_reply(:bad_event, uas, call)

      nil ->
        do_reply(:bad_event, uas, call)
    end
  end

  defp check_dialog(:ack, %Message{to_tag: nil}, uas, call) do
    Logger.notice("received out-of-dialog ACK")
    Call.update(call, %{uas | status: :finished})
  end

  defp check_dialog(:cancel, _req, uas, call), do: do_reply(:no_transaction, uas, call)

  # NOTIFYs outside of any subscription (unsolicited, as the message
  # waiting ones of many PBXs) go to sip_unsolicited_notify/2, without
  # creating dialogs
  defp check_dialog(:notify, %Message{to_tag: nil}, uas, call) do
    uas = %{uas | opts: [:no_dialog | uas.opts]}
    user_callback(uas, Call.update(call, uas))
  end

  defp check_dialog(method, %Message{to_tag: nil}, uas, call) when method in @in_dialog,
    do: do_reply(:no_transaction, uas, call)

  defp check_dialog(method, %Message{to_tag: nil} = req, uas, call),
    do: check_method(method, req, uas, call)

  defp check_dialog(method, req, %Trans{stateless: true} = uas, call),
    do: check_method(method, req, uas, call)

  defp check_dialog(method, req, uas, call) do
    req = Event.refer_id(req, call)
    uas = %{uas | request: req}

    case DialogUAS.request(req, call) do
      {:ok, call} ->
        check_method(method, req, uas, call)

      {:error, error} when method == :ack ->
        Logger.notice("ACK dialog error: #{inspect(error)}")
        Call.update(call, %{uas | status: :finished})

      {:error, reply} ->
        uas = %{uas | opts: [:no_dialog | uas.opts]}
        do_reply(reply, uas, Call.update(call, uas))
    end
  end

  defp check_method(:invite, _req, uas, call) do
    uas = Timers.expire(uas, :expire)
    user_callback(uas, Call.update(call, uas))
  end

  defp check_method(:ack, req, uas, call) do
    Call.callback(call, :sip_ack, [req, call])
    Call.update(call, %{uas | status: :finished})
  end

  defp check_method(:register, req, uas, call) do
    case {Message.header(req, "path"), "path" in req.supported} do
      {[], _} -> user_callback(uas, call)
      {_, true} -> user_callback(uas, call)
      {_, false} -> do_reply({:bad_extension, "path"}, uas, call)
    end
  end

  # The PRACK acknowledges the reliable response of an INVITE in progress
  defp check_method(:prack, req, uas, call) do
    with {:ok, rack} <- rack(req),
         %Trans{} = inv <- prack_trans(rack, req, call) do
      inv =
        %{inv | prack: nil, next_retrans: nil}
        |> Timers.retrans(:cancel, call)
        |> Timers.timeout(:timer_c, call)

      user_callback(uas, Call.update(call, inv))
    else
      :error -> do_reply({:invalid_request, "Invalid RAck"}, uas, call)
      nil -> do_reply(:no_transaction, uas, call)
    end
  end

  defp check_method(:refer, req, uas, call) do
    case Message.header(req, "refer-to") do
      [_] -> user_callback(uas, call)
      _ -> do_reply(:invalid_request, uas, call)
    end
  end

  defp check_method(method, _req, uas, call) when is_map_key(@callbacks, method),
    do: user_callback(uas, call)

  defp check_method(_method, _req, uas, call),
    do: do_reply({:method_not_allowed, call.config[:allow] || []}, uas, call)

  # RAck: RSeq, CSeq number and method
  defp rack(req) do
    with [value] <- Message.header(req, "rack"),
         [rseq, cseq, method] <- String.split(value),
         {rseq, ""} <- Integer.parse(rseq),
         {cseq, ""} <- Integer.parse(cseq) do
      {:ok, {rseq, cseq, Message.to_method(method)}}
    else
      _ -> :error
    end
  end

  defp prack_trans(rack, req, call) do
    Enum.find_value(call.trans, fn {_, t} ->
      if t.class == :uas and t.status == :invite_proceeding and t.prack == rack and
           t.request.dialog_id == req.dialog_id,
         do: t
    end)
  end

  defp user_callback(%Trans{method: method, request: req} = uas, call) do
    fun =
      case {method, req.to_tag} do
        {:invite, tag} when tag != nil -> :sip_reinvite
        {:subscribe, tag} when tag != nil -> :sip_resubscribe
        {:notify, nil} -> :sip_unsolicited_notify
        {method, _} -> Map.fetch!(@callbacks, method)
      end

    case Call.callback(call, fun, [req, call]) do
      {:reply, reply} -> do_reply(reply, uas, call)
      :noreply -> call
      other -> invalid_reply(fun, other, uas, call)
    end
  end

  ## ===================================================================
  ## Replies
  ## ===================================================================

  @doc false
  # Asynchronous reply to a request, identified by its message id
  def reply_id(msg_id, sipreply, call) do
    case Call.trans_by_msg(call, msg_id) do
      {:ok, %Trans{class: :uas} = uas} -> reply(sipreply, uas, call)
      _ -> {{:error, :invalid_request}, call}
    end
  end

  @doc false
  def do_reply(sipreply, uas, call), do: elem(reply(sipreply, uas, call), 1)

  @doc false
  # Sends a response in a server transaction
  def reply(_sipreply, %Trans{method: :ack} = uas, call),
    do: {{:error, :invalid_request}, Call.update(call, %{uas | status: :finished})}

  def reply(
        {%Message{class: {:resp, code, _}} = resp, opts},
        %Trans{status: status, code: last} = uas,
        call
      )
      when status in [:invite_proceeding, :trying, :proceeding] or
             (status in [:invite_accepted, :invite_confirmed, :completed] and code in 200..299 and
                last in 200..299) do
    {resp, opts} = DialogUAS.update_response(resp, opts, call)

    resp =
      if SessionTimer.enabled?(call.config) and not match?({:fork, _}, uas.from),
        do: SessionTimer.uas_response(uas.request, resp, call.config),
        else: resp

    case reliable(resp, uas) do
      {:ok, resp, uas} -> send_reply(resp, opts, uas, call)
      {:error, error} -> {{:error, error}, call}
    end
  end

  def reply({%Message{}, _opts}, _uas, call), do: {{:error, :invalid_request}, call}

  def reply(sipreply, %Trans{request: %Message{} = req} = uas, call),
    do: reply(Reply.make!(req, sipreply, call.config), uas, call)

  def reply(_sipreply, _uas, call), do: {{:error, :invalid_request}, call}

  # Reliable provisional responses (RFC 3262) get a RSeq, and only one can
  # be pending of its PRACK. Proxied responses are forwarded as they are
  # (their PRACKs go end to end).
  defp reliable(resp, %Trans{from: {:fork, _}} = uas), do: {:ok, resp, uas}

  defp reliable(%Message{class: {:resp, code, _}} = resp, uas) when code in 101..199 do
    cond do
      "100rel" not in resp.require ->
        {:ok, resp, uas}

      uas.stateless ->
        {:error, :stateless_not_allowed}

      uas.prack != nil ->
        {:error, :pending_prack}

      true ->
        rseq = if uas.rseq == 0, do: Enum.random(1..2_147_483_647), else: uas.rseq + 1
        {:ok, resp} = Message.update_header(resp, :replace, "rseq", rseq)
        {cseq, method} = resp.cseq
        {:ok, resp, %{uas | rseq: rseq, prack: {rseq, cseq, method}}}
    end
  end

  defp reliable(resp, uas), do: {:ok, resp, uas}

  defp send_reply(resp, opts, uas, call) do
    {user_reply, resp} =
      case Transp.send_response(resp, opts, call.config) do
        {:ok, resp} ->
          {:ok, resp}

        {:error, error} ->
          Logger.notice("could not send response: #{inspect(error)}")
          {resp, _} = Reply.make!(uas.request, :service_unavailable, call.config)
          {{:error, :service_unavailable}, resp}
      end

    {:resp, code, _} = resp.class
    if code >= 200 and uas.code < 200, do: Call.telemetry(:uas, uas, code, call)
    uas = %{uas | response: resp, code: code}
    call = sent_dialog(resp, opts, uas, Call.put_msg(call, resp, uas.id))

    # A final response ends the wait for a PRACK
    uas =
      if code >= 200 and uas.prack != nil,
        do: Timers.retrans(%{uas | prack: nil, next_retrans: nil}, :cancel, call),
        else: uas

    if uas.stateless and uas.method != :invite do
      {user_reply, Call.update(call, %{uas | status: :finished})}
    else
      {user_reply, Call.update(call, sent_reply(uas.status, code, uas, call))}
    end
  end

  # Dialog changes after sending a response. The origin of a request
  # accepted with a 2xx is authorized in its dialog.
  defp sent_dialog(%Message{class: {:resp, code, _}} = resp, opts, uas, call) do
    call =
      if uas.stateless or :no_dialog in uas.opts or :no_dialog in opts,
        do: call,
        else: DialogUAS.response(uas.request, resp, call)

    if code in 200..299,
      do: Auth.update(call, %{uas.request | dialog_id: resp.dialog_id}),
      else: call
  end

  # State machine after sending a response (RFC 3261 §17.2 and RFC 6026).
  # A reliable provisional response is retransmitted until the PRACK.
  defp sent_reply(:invite_proceeding, code, uas, call) when code < 200 do
    cond do
      "100rel" in uas.response.require ->
        %{uas | next_retrans: nil}
        |> Timers.timeout(:prack_timeout, call)
        |> Timers.retrans(:prack_retrans, call)

      # Waiting for a PRACK
      uas.prack != nil ->
        uas

      true ->
        Timers.timeout(uas, :timer_c, call)
    end
  end

  # Accepted: absorbs INVITE retransmissions, the dialog retransmits the 2xx
  defp sent_reply(:invite_proceeding, code, uas, call) when code < 300 do
    %{uas | status: :invite_accepted, response: nil}
    |> Timers.expire(:cancel)
    |> Timers.timeout(:timer_l, call)
  end

  defp sent_reply(:invite_proceeding, _code, uas, call) do
    uas =
      %{uas | status: :invite_completed}
      |> Timers.expire(:cancel)
      |> Timers.timeout(:timer_h, call)

    if uas.transport == :udp,
      do: Timers.retrans(uas, :timer_g, call),
      else: %{uas | response: nil}
  end

  defp sent_reply(:trying, code, uas, call),
    do: sent_reply(:proceeding, code, %{uas | status: :proceeding}, call)

  defp sent_reply(:proceeding, code, uas, _call) when code < 200, do: uas

  defp sent_reply(:proceeding, _code, uas, call) do
    if uas.transport == :udp,
      do: Timers.timeout(%{uas | status: :completed}, :timer_j, call),
      else: %{uas | status: :finished}
  end

  defp sent_reply(_status, _code, uas, _call), do: uas

  @doc false
  # Stateless response, outside any call process (for example when the call
  # cannot be started)
  def reply_stateless(%Message{} = req, sipreply) do
    req = preprocess(req)
    {resp, opts} = Reply.make!(req, sipreply, Caracola.Call.config(req.service))
    Transp.send_response(resp, opts, [])
  end

  ## ===================================================================
  ## Timers
  ## ===================================================================

  @doc false
  def timer(:timer_c, uas, call), do: do_reply({:timeout, "Timer C Timeout"}, uas, call)
  def timer(:noinvite, uas, call), do: do_reply({:timeout, "No-INVITE Timeout"}, uas, call)

  def timer(:timer_g, %Trans{response: resp} = uas, call) do
    case Transp.resend_response(resp) do
      {:ok, _} -> Call.update(call, Timers.retrans(uas, :timer_g, call))
      {:error, _} -> Call.update(call, %{uas | status: :finished})
    end
  end

  def timer(:prack_retrans, %Trans{status: :invite_proceeding, prack: {_, _, _}} = uas, call) do
    case Transp.resend_response(uas.response) do
      {:ok, _} -> Call.update(call, Timers.retrans(uas, :prack_retrans, call))
      {:error, _} -> Call.update(call, %{uas | status: :finished})
    end
  end

  def timer(:prack_retrans, uas, call), do: Call.update(call, uas)

  def timer(:prack_timeout, uas, call) do
    uas = %{uas | prack: nil}
    do_reply({:internal_error, "Reliable Provisional Response Timeout"}, uas, call)
  end

  def timer(tag, uas, call) when tag in [:timer_h, :timer_i, :timer_j, :timer_l],
    do: Call.update(call, %{uas | status: :finished})

  def timer(:expire, %Trans{status: :invite_proceeding} = uas, call) do
    uas = %{uas | cancel: :cancelled}
    do_reply(:request_terminated, uas, Call.update(call, uas))
  end

  def timer(:expire, uas, call), do: Call.update(call, uas)
end
