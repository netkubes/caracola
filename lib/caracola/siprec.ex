defmodule Caracola.Siprec do
  @moduledoc """
  Session recording (SIPREC, RFC 7866): a session recording client (SRC)
  records a call by starting a *recording session* with a session
  recording server (SRS): an INVITE whose body has the SDP of the media
  streams sent to the SRS and the recording metadata (RFC 7865,
  `application/rs-metadata+xml`), that says who the participants are and
  which stream each one sends.

  As SRC, `record/4` starts a recording session:

  ```
  recording = %{
    call_id: "the Call-ID of the recorded call",
    participants: [
      %{aor: "sip:alice@example.com", name: "Alice", send: [1]},
      %{aor: "sip:bob@example.com", send: [2]}
    ],
    sdp: sdp
  }

  {:ok, 200, [dialog: dialog]} = Caracola.Siprec.record(MySRC, "sip:srs@rec.example.com", recording)
  # ...
  Caracola.UAC.bye(dialog)
  ```

  `sdp` has one media for each stream (`send: [1]` is the first one),
  with the address where the media of that stream is sent from: copying
  the RTP of the call to the SRS is up to the application (usually, a
  media server or relay). The medias get a `label` attribute with their
  number and are `sendonly`. With `Caracola.B2BUA`, `bridge/2` builds the
  recording of a bridged call.

  As SRS, a service with this plugin accepts `Require: siprec`;
  `recording_session?/1` tells if an INVITE is a recording session (its
  Contact has the `+sip.src` feature tag), and `decode/1` returns its SDP
  and metadata. Recording the media is up to the application.

  Not yet: updating the metadata during the session, pausing and
  resuming, and the `+sip.srs` and recording-aware UA indications.
  """

  use Malla.Plugin, plugin_deps: [Caracola]

  alias Caracola.{B2BUA, Dialog, Message, SDP, Tokens, UAC, Util, XML}

  @metadata_type "application/rs-metadata+xml"
  @ns "urn:ietf:params:xml:ns:recording:1"

  @typedoc """
  A participant of a recording: its address (and optional name), and the
  numbers (from 1) of the medias of the SDP it sends.
  """
  @type participant :: %{
          required(:aor) => String.t(),
          optional(:name) => String.t() | nil,
          required(:send) => [pos_integer()]
        }

  @typedoc """
  A recording, for `record/4`: the participants, the SDP with one media
  per stream, the Call-ID of the recorded call (optional) and the session
  id of the recording (optional, generated by default).
  """
  @type recording :: %{
          required(:participants) => [participant()],
          required(:sdp) => SDP.t(),
          optional(:call_id) => String.t() | nil,
          optional(:session_id) => String.t()
        }

  @typedoc "The metadata of a recording session, as returned by `decode_metadata/1`."
  @type metadata :: %{
          session_id: String.t() | nil,
          call_id: String.t() | nil,
          start_time: String.t() | nil,
          participants: [
            %{
              id: String.t(),
              aor: String.t() | nil,
              name: String.t() | nil,
              send: [String.t()],
              recv: [String.t()]
            }
          ],
          streams: [%{id: String.t(), label: String.t() | nil}]
        }

  ## ===================================================================
  ## SRC
  ## ===================================================================

  @doc """
  Starts a recording session with the SRS at `uri`: an INVITE with the
  SDP and the metadata of the recording (see the module documentation),
  `Require: siprec` and the `+sip.src` feature tag. `opts` are options of
  `Caracola.UAC.invite/3`; the ACK is sent automatically. End it with
  `Caracola.UAC.bye/2`.
  """
  @spec record(module(), String.t() | Caracola.URI.t(), recording(), list()) :: UAC.result()
  def record(service, uri, recording, opts \\ []) do
    boundary = "caracola-" <> Util.uid()
    sdp = label(recording.sdp)

    body =
      multipart(boundary, [
        {"application/sdp", [], SDP.encode(sdp)},
        {@metadata_type, [{"Content-Disposition", "recording-session"}],
         encode_metadata(recording)}
      ])

    opts = [
      :auto_2xx_ack,
      {:body, body},
      {:content_type, "multipart/mixed;boundary=#{boundary}"},
      {:replace, "require", "siprec"},
      {:contact_params, [{"+sip.src", nil}]} | opts
    ]

    UAC.invite(service, uri, opts)
  end

  @doc """
  The recording of a call bridged by `Caracola.B2BUA`: the remote party
  of the A leg sends the first media of `sdp`, and the one of the B leg
  the second one.
  """
  @spec bridge(B2BUA.t(), SDP.t()) :: {:ok, recording()} | {:error, term()}
  def bridge(%B2BUA{status: :answered, a: a, b: b} = bridge, %SDP{} = sdp) do
    with {:ok, a} <- Dialog.get(a),
         {:ok, b} <- Dialog.get(b) do
      {:ok,
       %{
         call_id: bridge.a_call_id,
         participants: [participant(a.remote_uri, [1]), participant(b.remote_uri, [2])],
         sdp: sdp
       }}
    end
  end

  def bridge(%B2BUA{}, _sdp), do: {:error, :not_answered}

  defp participant(uri, send) do
    %{aor: Caracola.Notifier.uri({uri.scheme, uri.user, uri.domain}), name: uri.disp, send: send}
  end

  # Each media gets its number as label, and is sendonly
  defp label(%SDP{medias: medias} = sdp) do
    medias =
      for {media, n} <- Enum.with_index(medias, 1) do
        attrs = Enum.reject(media.attributes, fn {name, _} -> name == "label" end)
        %{media | attributes: attrs ++ [{"label", [Integer.to_string(n)]}]}
      end

    SDP.update(%{sdp | medias: medias}, :sendonly)
  end

  @doc """
  Encodes the metadata of a recording (RFC 7865), with the time of now as
  start time.
  """
  @spec encode_metadata(recording()) :: binary()
  def encode_metadata(recording) do
    session = Map.get(recording, :session_id) || id()
    time = DateTime.utc_now() |> DateTime.truncate(:second) |> DateTime.to_iso8601()
    streams = for n <- 1..length(recording.sdp.medias)//1, into: %{}, do: {n, id()}
    participants = for p <- recording.participants, do: {id(), p}

    IO.iodata_to_binary([
      ~s(<?xml version="1.0" encoding="UTF-8"?>\n),
      ~s(<recording xmlns="#{@ns}">\n),
      "<datamode>complete</datamode>\n",
      ~s(<session session_id="#{session}">\n),
      if(recording[:call_id], do: [XML.tag("sipSessionID", recording.call_id), "\n"], else: []),
      XML.tag("start-time", time),
      "\n</session>\n",
      Enum.map(participants, &encode_participant/1),
      for {n, sid} <- streams do
        ~s(<stream stream_id="#{sid}" session_id="#{session}"><label>#{n}</label></stream>\n)
      end,
      ~s(<sessionrecordingassoc session_id="#{session}">),
      XML.tag("associate-time", time),
      "</sessionrecordingassoc>\n",
      Enum.map(participants, &encode_assocs(&1, session, streams, time)),
      "</recording>\n"
    ])
  end

  defp encode_participant({pid, p}) do
    name = if p[:name], do: XML.tag("name", p.name), else: ""

    [
      ~s(<participant participant_id="#{pid}">),
      ~s(<nameID aor="#{XML.escape(p.aor)}">#{name}</nameID></participant>\n)
    ]
  end

  defp encode_assocs({pid, p}, session, streams, time) do
    sends = for n <- p.send, sid = streams[n], sid != nil, do: XML.tag("send", sid)
    recvs = for {n, sid} <- streams, n not in p.send, do: XML.tag("recv", sid)

    [
      ~s(<participantsessionassoc participant_id="#{pid}" session_id="#{session}">),
      XML.tag("associate-time", time),
      "</participantsessionassoc>\n",
      ~s(<participantstreamassoc participant_id="#{pid}">),
      sends,
      recvs,
      "</participantstreamassoc>\n"
    ]
  end

  defp id, do: Base.url_encode64(:crypto.strong_rand_bytes(16), padding: false)

  ## ===================================================================
  ## SRS
  ## ===================================================================

  @doc "Returns `true` if a request comes from an SRC (its Contact has `+sip.src`)."
  @spec recording_session?(Message.t()) :: boolean()
  def recording_session?(%Message{contacts: contacts}),
    do: Enum.any?(contacts, &List.keymember?(&1.ext_params, "+sip.src", 0))

  @doc """
  The SDP and the metadata of the body of a recording session request.
  """
  @spec decode(Message.t()) :: {:ok, %{sdp: SDP.t() | nil, metadata: metadata()}} | :error
  def decode(%Message{content_type: {type, params}, body: body}) when is_binary(body) do
    with "multipart/mixed" <- Util.ascii_downcase(type),
         {_, boundary} <- List.keyfind(params, "boundary", 0),
         parts = parts(body, String.trim(boundary, "\"")),
         {_, _, xml} <- Enum.find(parts, &(elem(&1, 0) == @metadata_type)),
         {:ok, metadata} <- decode_metadata(xml) do
      sdp =
        case Enum.find(parts, &(elem(&1, 0) == "application/sdp")) do
          {_, _, sdp} -> elem(SDP.parse(sdp), 1)
          nil -> nil
        end

      {:ok, %{sdp: if(is_struct(sdp, SDP), do: sdp), metadata: metadata}}
    else
      _ -> :error
    end
  end

  def decode(%Message{}), do: :error

  @doc """
  Parses recording metadata. The streams sent and received by each
  participant are given by their labels (the media numbers).
  """
  @spec decode_metadata(binary()) :: {:ok, metadata()} | :error
  def decode_metadata(xml) do
    case XML.parse(xml) do
      {:ok, {"recording", _, _} = root} ->
        session = XML.child(root, "session")

        streams =
          for s <- XML.children(root, "stream"),
              do: %{id: XML.attr(s, "stream_id"), label: XML.text(XML.child(s, "label"))}

        labels = Map.new(streams, &{&1.id, &1.label})

        assocs =
          Map.new(
            XML.children(root, "participantstreamassoc"),
            &{XML.attr(&1, "participant_id"), &1}
          )

        participants =
          for p <- XML.children(root, "participant") do
            id = XML.attr(p, "participant_id")
            name_id = XML.child(p, "nameID")
            assoc = assocs[id]

            %{
              id: id,
              aor: XML.attr(name_id, "aor"),
              name: XML.text(XML.child(name_id, "name")),
              send: for(s <- children(assoc, "send"), do: labels[XML.text(s)] || XML.text(s)),
              recv: for(s <- children(assoc, "recv"), do: labels[XML.text(s)] || XML.text(s))
            }
          end

        {:ok,
         %{
           session_id: XML.attr(session, "session_id"),
           call_id: XML.text(XML.child(session, "sipSessionID")),
           start_time: XML.text(XML.child(session, "start-time")),
           participants: participants,
           streams: streams
         }}

      _ ->
        :error
    end
  end

  defp children(nil, _name), do: []
  defp children(element, name), do: XML.children(element, name)

  ## ===================================================================
  ## Multipart
  ## ===================================================================

  defp multipart(boundary, parts) do
    IO.iodata_to_binary([
      for {type, headers, body} <- parts do
        [
          "--",
          boundary,
          "\r\nContent-Type: ",
          type,
          "\r\n",
          for({name, value} <- headers, do: [name, ": ", value, "\r\n"]),
          "\r\n",
          body,
          "\r\n"
        ]
      end,
      "--",
      boundary,
      "--\r\n"
    ])
  end

  # The parts of a multipart body, as {content_type, headers, body}
  defp parts(body, boundary) do
    body
    |> String.split("--" <> boundary)
    |> Enum.drop(1)
    |> Enum.take_while(&(not String.starts_with?(&1, "--")))
    |> Enum.flat_map(&part/1)
  end

  defp part(part) do
    case String.split(String.trim_leading(part, "\r\n"), "\r\n\r\n", parts: 2) do
      [head, content] ->
        headers =
          for line <- String.split(head, "\r\n"),
              [name, value] <- [String.split(line, ":", parts: 2)],
              do: {Util.ascii_downcase(String.trim(name)), String.trim(value)}

        type =
          case List.keyfind(headers, "content-type", 0) do
            {_, value} -> content_type(value)
            nil -> "text/plain"
          end

        [{type, headers, String.replace_suffix(content, "\r\n", "")}]

      _ ->
        []
    end
  end

  defp content_type(value) do
    case Tokens.parse(value) do
      {:ok, [{type, _} | _]} -> Util.ascii_downcase(type)
      _ -> value
    end
  end

  ## ===================================================================
  ## Plugin
  ## ===================================================================

  @impl true
  def plugin_config(_srv_id, config),
    do: {:ok, Caracola.Config.add_values(config, :supported, ["siprec"])}
end
